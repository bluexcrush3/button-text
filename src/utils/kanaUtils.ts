import { KanaGroup, KANA_GROUPS } from '../types';

export { KANA_GROUPS };
export type { KanaGroup };

/**
 * 部屋名・場所名などの文字列から、五十音の行（あ、か、さ、た、な、は、ま、や、ら、わ、A）を自動判定する
 */
export function detectKanaGroup(name: string): KanaGroup {
  if (!name || !name.trim()) return 'あ';
  const trimmed = name.trim();
  const firstChar = trimmed[0];

  // 1. 英数字・記号で始まる場合
  if (/^[a-zA-Z0-9０-９]/.test(firstChar)) {
    return 'A';
  }

  // 2. 代表的な部屋名・建築用語のプレフィックス判定
  const prefixMap: { pattern: RegExp; group: KanaGroup }[] = [
    // あ行
    {
      pattern: /^(植込|植栽|アプローチ|ウッドデッキ|エントランス|応接|押入|押し入れ|踊り場|屋上|屋外|居間|居室|インナー|アトリエ|オープンテラス|雨戸|愛犬)/,
      group: 'あ',
    },
    // か行
    {
      pattern: /^(外構|階段|勝手口|家事室|ガレージ|車庫|給湯|玄関|客間|キッチン|クローゼット|子供|子ども|個室|共用|管理人|乾熱|機械)/,
      group: 'か',
    },
    // さ行
    {
      pattern: /^(洗面|書斎|寝室|主寝室|収納|シューズ|サンルーム|食品庫|サービスルーム|脱衣洗面|シャワー|シアター|作業)/,
      group: 'さ',
    },
    // た行
    {
      pattern: /^(建物|土間|台所|脱衣|ダイニング|トイレ|テラス|床の間|地下|茶室|畳|手洗い|手洗|タタミ|デッキ)/,
      group: 'た',
    },
    // な行
    {
      pattern: /^(納戸|納屋|庭|中庭|物干)/, // 物干し場等は「ほ」または「な」だが、庭・納戸が主流
      group: 'な',
    },
    // は行
    {
      pattern: /^(塀|風呂|便所|バルコニー|ベランダ|パントリー|ホール|風除室|ポーチ|ファミリー|仏間|配電|防音|保管|パウダールーム)/,
      group: 'は',
    },
    // ま行
    {
      pattern: /^(物置|水回|水まわり|マイルーム|待合|物干し)/,
      group: 'ま',
    },
    // や行
    {
      pattern: /^(擁壁|洋室|浴室|ユーティリティ|湯沸)/,
      group: 'や',
    },
    // ら行
    {
      pattern: /^(廊下|リビング|ロフト|ランドリー|リネン|ルーム)/,
      group: 'ら',
    },
    // わ行
    {
      pattern: /^(和室|ワーク|ウォーク)/,
      group: 'わ',
    },
  ];

  for (const item of prefixMap) {
    if (item.pattern.test(trimmed)) {
      return item.group;
    }
  }

  // 3. ひらがな・カタカナの先頭文字判定
  const code = firstChar.charCodeAt(0);
  let hira = firstChar;
  if (code >= 0x30a1 && code <= 0x30f6) {
    // 全角カタカナをひらがなに変換
    hira = String.fromCharCode(code - 0x60);
  }

  if (/^[ぁ-おゔ]/.test(hira)) return 'あ';
  if (/^[か-ごヵヶ]/.test(hira)) return 'か';
  if (/^[さ-ぞ]/.test(hira)) return 'さ';
  if (/^[た-どっ]/.test(hira)) return 'た';
  if (/^[な-の]/.test(hira)) return 'な';
  if (/^[は-ぽ]/.test(hira)) return 'は';
  if (/^[ま-も]/.test(hira)) return 'ま';
  if (/^[ゃ-よ]/.test(hira)) return 'や';
  if (/^[ら-ろ]/.test(hira)) return 'ら';
  if (/^[ゎ-ん]/.test(hira)) return 'わ';

  // 4. 先頭の漢字ごとの辞書（建築・住宅で頻出の漢字）
  const kanjiToKana: Record<string, KanaGroup> = {
    // あ行
    '植': 'あ', '応': 'あ', '押': 'あ', '踊': 'あ', '屋': 'あ', '居': 'あ', '雨': 'あ', '網': 'あ', '縁': 'あ', '愛': 'あ',
    '安': 'あ', '暗': 'あ', '遺': 'あ', '育': 'あ', '一': 'あ', '奥': 'あ', '音': 'あ', '板': 'あ',
    // か行
    '外': 'か', '階': 'か', '勝': 'か', '車': 'か', '庫': 'か', '給': 'か', '玄': 'か', '客': 'か', '家': 'か',
    '開': 'か', '間': 'か', '乾': 'か', '換': 'か', '館': 'か', '機': 'か', '共': 'か', '具': 'か', '構': 'か', '金': 'か',
    // さ行
    '洗': 'さ', '書': 'さ', '寝': 'さ', '主': 'さ', '収': 'さ', '食': 'さ', '採': 'さ', '吹': 'さ', '設': 'さ', '専': 'さ',
    '西': 'さ', '作': 'さ', '酒': 'さ', '室': 'さ', '製': 'さ',
    // た行
    '建': 'た', '土': 'た', '台': 'た', '脱': 'た', '床': 'た', '地': 'た', '茶': 'た', '畳': 'た', '棚': 'た', '天': 'た',
    '手': 'た', '東': 'た', '通': 'た', '炊': 'た',
    // な行
    '納': 'な', '庭': 'な', '中': 'な', '南': 'な',
    // は行
    '塀': 'は', '風': 'は', '便': 'は', '仏': 'は', '配': 'は', '箱': 'は', '庇': 'は', '防': 'は', '歩': 'は', '北': 'は',
    '母': 'は', '別': 'は', '本': 'は', '柱': 'は', '壁': 'は', '保': 'は',
    // ま行
    '物': 'ま', '水': 'ま', '窓': 'ま', '待': 'ま', '門': 'ま',
    // や行
    '擁': 'や', '洋': 'や', '浴': 'や', '役': 'や', '予': 'や', '湯': 'や', '夜': 'や', '山': 'や',
    // ら行
    '廊': 'ら', '霊': 'ら', '連': 'ら', '来': 'ら', '理': 'ら', '寮': 'ら', '冷': 'ら',
    // わ行
    '和': 'わ',
  };

  if (kanjiToKana[firstChar]) {
    return kanjiToKana[firstChar];
  }

  // 辞書にない漢字の場合はデフォルトで「あ」
  return 'あ';
}
